create or replace function public.online_room_is_open(r public.online_rooms)
returns boolean language sql stable security definer set search_path = '' as $$
  select r.closed_at is null and
    (r.official or (r.host_id is not null and
      coalesce((select m.last_seen from public.online_room_members m where m.room_id=r.id and m.user_id=r.host_id),r.created_at)
        > now() - interval '3 minutes'))
$$;

create or replace function public.online_room_display_name(raw text)
returns text language sql immutable set search_path = '' as $$
  select case when length(btrim(coalesce(raw,'')))=0 or position('@' in raw)>0 then 'Người học'
    else left(btrim(raw),60) end
$$;
create or replace function public.online_room_card(r public.online_rooms)
returns jsonb language sql stable security definer set search_path = '' as $$
  select jsonb_build_object('id',r.id,'kind',r.kind,'name',r.name,'topic',r.topic,'visibility',r.visibility,
    'layout',r.layout,'official',r.official,'music_enabled',r.music_enabled,'requires_approval',r.requires_approval,
    'host_id',r.host_id,'host_name',case when r.official then 'MindCanvas' else
      public.online_room_display_name((select p.display_name from public.profiles p where p.id=r.host_id)) end,
    'occupancy',(select count(*) from public.online_room_members m where m.room_id=r.id and m.lease_until>now()),
    'capacity',20)
$$;

create or replace function public.online_room_can_host_public()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.online_room_public_hosts where user_id=auth.uid())
$$;
create or replace function public.online_room_can_manage(r public.online_rooms)
returns boolean language sql stable security definer set search_path = '' as $$
  select coalesce(r.host_id=auth.uid(),false) or (r.official and public.online_room_can_host_public())
$$;

-- Broadcast a wake-up only: state, messages and people are fetched again under current permissions.
create or replace function public.online_room_notify(p_room uuid, p_area text)
returns void language plpgsql security definer set search_path = '' as $$
begin
  perform realtime.send(jsonb_build_object('area',p_area),'changed','mindcanvas-online-room:'||p_room::text,true);
exception when others then
  -- Database Broadcast may be unavailable while the first Realtime partition starts.
  -- Reads and writes must not depend on this notification; clients also reconcile by polling.
  return;
end;
$$;

create or replace function public.online_room_can_listen(p_topic text)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists(
    select 1 from public.online_room_members m join public.online_rooms r on r.id=m.room_id
    where m.user_id=auth.uid() and m.lease_until>now() and public.online_room_is_open(r)
      and p_topic='mindcanvas-online-room:'||m.room_id::text)
$$;
drop policy if exists "Online room private wakeups" on realtime.messages;
create policy "Online room private wakeups" on realtime.messages for select to authenticated
  using (extension='broadcast' and public.online_room_can_listen((select realtime.topic())));
-- Keep older unrelated realtime policies; ensure future permissive policies cannot open this topic prefix.
drop policy if exists "Online room topic scope" on realtime.messages;
create policy "Online room topic scope" on realtime.messages as restrictive for select to authenticated
  using (coalesce((select realtime.topic()),'') not like 'mindcanvas-online-room:%'
      or public.online_room_can_listen((select realtime.topic())));
drop policy if exists "Online room events server only" on realtime.messages;
create policy "Online room events server only" on realtime.messages as restrictive for insert to authenticated
  with check (coalesce((select realtime.topic()),'') not like 'mindcanvas-online-room:%');

create or replace function public.online_room_avatar_allowed(p_path text)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists(
    select 1 from public.online_room_members viewer join public.online_rooms r on r.id=viewer.room_id
      join public.online_room_members person on person.room_id=r.id
      join public.account_profile_details d on d.user_id=person.user_id
    where viewer.user_id=auth.uid() and viewer.lease_until>now() and person.lease_until>now()
      and p_path = person.user_id::text||'/avatar-'||d.avatar_slot::text||'.jpg' and public.online_room_is_open(r))
$$;
drop policy if exists "Online room participant avatars" on storage.objects;
create policy "Online room participant avatars" on storage.objects for select to authenticated
  using (bucket_id='profile-avatars' and public.online_room_avatar_allowed(name));

create or replace function public.list_online_rooms()
returns jsonb language sql stable security definer set search_path = '' as $$
  select jsonb_build_object(
    'can_create_public',public.online_room_can_host_public(),
    'rooms',coalesce((select jsonb_agg(public.online_room_card(x) order by x.official desc,x.created_at desc)
      from (select r.* from public.online_rooms r where auth.uid() is not null and r.closed_at is null
        and (r.visibility='public' or r.host_id=auth.uid() or exists(
          select 1 from public.online_room_members m where m.room_id=r.id and m.user_id=auth.uid() and m.admission<>'removed'))
        and public.online_room_is_open(r)
        order by r.official desc,r.created_at desc,r.id limit 60) x),'[]'::jsonb))
$$;

create or replace function public.create_online_music_room(p_name text,p_topic text,p_visibility text,p_layout text,p_approval boolean,p_suggestions boolean)
returns uuid language plpgsql security definer set search_path = '' as $$
declare u uuid:=auth.uid(); room uuid;
begin
  if u is null then raise exception 'ONLINE_AUTH'; end if;
  if p_name is null or length(btrim(p_name)) not between 1 and 64 or length(coalesce(p_topic,''))>160
    or p_visibility is null or p_visibility not in ('public','private') or p_layout is null or p_layout not in ('classroom','compact') then raise exception 'ONLINE_INPUT'; end if;
  if p_visibility='public' and not public.online_room_can_host_public() then raise exception 'ONLINE_PUBLIC_DENIED'; end if;
  perform pg_advisory_xact_lock(hashtextextended(u::text,6000));
  if exists(select 1 from public.online_rooms r where (r.created_by=u or r.host_id=u) and not r.official
    and public.online_room_is_open(r)) then raise exception 'ONLINE_ROOM_LIMIT'; end if;
  insert into public.online_rooms(created_by,host_id,name,topic,visibility,layout,requires_approval,suggestions)
    values(u,u,btrim(p_name),btrim(coalesce(p_topic,'')),p_visibility,p_layout,p_visibility='private' and coalesce(p_approval,true),coalesce(p_suggestions,false))
    returning id into room;
  return room;
end;
$$;

create or replace function public.join_online_room(p_room uuid,p_client uuid,p_invite text default null)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare u uuid:=auth.uid(); r public.online_rooms; m public.online_room_members;
  target_seat smallint; expired integer; membership_changed boolean;
begin
  if u is null or p_client is null then raise exception 'ONLINE_AUTH'; end if;
  select * into r from public.online_rooms where id=p_room for update;
  if r.id is null then return jsonb_build_object('state','closed'); end if;
  select * into m from public.online_room_members where room_id=p_room and user_id=u;
  if m.admission='removed' then return jsonb_build_object('state','removed'); end if;
  if not public.online_room_is_open(r) then return jsonb_build_object('state','closed'); end if;
  if r.visibility='private' and r.host_id<>u and m.user_id is null then
    if p_invite is null or p_invite !~ '^[a-f0-9]{64}$' or r.invite_expires_at is null or r.invite_expires_at<=now()
      or r.invite_hash is distinct from sha256(convert_to(p_invite,'UTF8'))
      then return jsonb_build_object('state','invite_required'); end if;
    if r.requires_approval then
      if (select count(*) from public.online_room_members where room_id=p_room and admission='waiting')>=40
        then return jsonb_build_object('state','waiting_full'); end if;
      insert into public.online_room_members(room_id,user_id,admission) values(p_room,u,'waiting');
      perform public.online_room_notify(p_room,'room');
      return jsonb_build_object('state','waiting','name',r.name);
    end if;
  end if;
  if m.admission='waiting' then return jsonb_build_object('state','waiting','name',r.name); end if;
  update public.online_room_members set seat=null,client_id=null,lease_until=null
    where room_id=p_room and lease_until<=now();
  get diagnostics expired=row_count;
  target_seat:=case when m.lease_until>now() then m.seat else null end;
  membership_changed:=target_seat is null or m.client_id is distinct from p_client or expired>0;
  if target_seat is null then
    select n into target_seat from generate_series(1,20) n where not exists(
      select 1 from public.online_room_members x where x.room_id=p_room and x.seat=n) order by n limit 1;
    if target_seat is null then return jsonb_build_object('state','full'); end if;
  end if;
  insert into public.online_room_members(room_id,user_id,seat,client_id,lease_until,last_seen)
    values(p_room,u,target_seat,p_client,now()+interval '90 seconds',now())
    on conflict(room_id,user_id) do update set seat=excluded.seat,client_id=excluded.client_id,
      lease_until=excluded.lease_until,last_seen=excluded.last_seen;
  if membership_changed then perform public.online_room_notify(p_room,'room'); end if;
  return jsonb_build_object('state','active','name',r.name);
end;
$$;

create or replace function public.online_room_session_state(r public.online_rooms,p_client uuid)
returns text language plpgsql stable security definer set search_path = '' as $$
declare m public.online_room_members;
begin
  if auth.uid() is null then raise exception 'ONLINE_AUTH'; end if;
  if r.id is null then return 'closed'; end if;
  select * into m from public.online_room_members where room_id=r.id and user_id=auth.uid();
  if m.admission='removed' then return 'removed'; end if;
  if not public.online_room_is_open(r) then return 'closed'; end if;
  if m.admission='waiting' then return 'waiting'; end if;
  if m.lease_until is null or m.lease_until<=now() then return 'expired'; end if;
  if m.client_id is distinct from p_client then return 'other_tab'; end if;
  return 'active';
end;
$$;

create or replace function public.ping_online_room(p_room uuid,p_client uuid,p_leave boolean default false)
returns text language plpgsql security definer set search_path = '' as $$
declare r public.online_rooms; state text;
begin
  select * into r from public.online_rooms where id=p_room for update;
  state:=public.online_room_session_state(r,p_client);
  if p_leave and state='waiting' then
    delete from public.online_room_members where room_id=p_room and user_id=auth.uid() and admission='waiting';
    perform public.online_room_notify(p_room,'room');
    return 'left';
  end if;
  if state<>'active' then return state; end if;
  if p_leave then
    update public.online_room_members set seat=null,lease_until=null,client_id=null,last_seen=now()
      where room_id=p_room and user_id=auth.uid() and client_id=p_client;
    perform public.online_room_notify(p_room,'room');
    return 'left';
  end if;
  update public.online_room_members set lease_until=now()+interval '90 seconds',last_seen=now()
    where room_id=p_room and user_id=auth.uid() and client_id=p_client;
  return 'active';
end;
$$;

create or replace function public.read_online_room(p_room uuid,p_client uuid)
returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare r public.online_rooms; state text; moderator boolean;
begin
  select * into r from public.online_rooms where id=p_room;
  state:=public.online_room_session_state(r,p_client);
  if state<>'active' then return jsonb_build_object('state',state); end if;
  moderator:=public.online_room_can_manage(r);
  return jsonb_build_object('state','active','room',public.online_room_card(r),'server_time',statement_timestamp(),
    'can_manage',moderator,'suggestions',r.suggestions,
    'playback',jsonb_build_object('video_id',r.video_id,'title',r.video_title,'attribution',r.attribution,'playing',r.is_playing,
      'loop',r.play_loop,'offset',r.play_offset,'at',r.play_at,'revision',r.play_rev),
    'members',coalesce((select jsonb_agg(jsonb_build_object('id',m.user_id,'seat',m.seat,
      'name',public.online_room_display_name(p.display_name),'avatar_url',p.avatar_url,'avatar_slot',d.avatar_slot,'avatar_revision',d.avatar_revision)
      order by m.seat) from public.online_room_members m left join public.profiles p on p.id=m.user_id
      left join public.account_profile_details d on d.user_id=m.user_id
      where m.room_id=p_room and m.lease_until>now()),'[]'::jsonb),
    'waiting',case when moderator then coalesce((select jsonb_agg(jsonb_build_object('id',m.user_id,
      'name',public.online_room_display_name(p.display_name)) order by m.joined_at)
      from public.online_room_members m left join public.profiles p on p.id=m.user_id
      where m.room_id=p_room and m.admission='waiting'),'[]'::jsonb) else '[]'::jsonb end,
    'queue',coalesce((select jsonb_agg(jsonb_build_object('id',q.id,'video_id',q.video_id,'title',q.title,'status',q.status,
      'requested_by',q.requested_by,'name',public.online_room_display_name(p.display_name)) order by q.sort_key,q.id)
      from public.online_room_tracks q left join public.profiles p on p.id=q.requested_by
      where q.room_id=p_room and (q.status='queued' or moderator or q.requested_by=auth.uid())),'[]'::jsonb));
end;
$$;

create or replace function public.read_online_room_chat(p_room uuid,p_client uuid)
returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare r public.online_rooms; state text;
begin
  select * into r from public.online_rooms where id=p_room;
  state:=public.online_room_session_state(r,p_client);
  if state<>'active' then return jsonb_build_object('state',state); end if;
  return jsonb_build_object('state','active','messages',coalesce((
    select jsonb_agg(jsonb_build_object('id',m.id::text,'author_id',m.author_id,
      'name',public.online_room_display_name(p.display_name),'body',m.body,'created_at',m.created_at) order by m.id)
    from (select * from public.online_room_chat where room_id=p_room order by id desc limit 80) m
    left join public.profiles p on p.id=m.author_id),'[]'::jsonb));
end;
$$;

create or replace function public.act_online_room(p_room uuid,p_client uuid,p_action text,p_payload jsonb default '{}'::jsonb)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare r public.online_rooms; moderator boolean; u uuid:=auth.uid(); state text;
  str text; label text; target uuid; row_id bigint; n integer; now_at timestamptz:=now(); q public.online_room_tracks;
  peer_key bigint; next_track public.online_room_tracks; reply jsonb:='{}'::jsonb; area text:='room';
begin
  select * into r from public.online_rooms where id=p_room for update;
  state:=public.online_room_session_state(r,p_client);
  if state<>'active' then return jsonb_build_object('state',state); end if;
  if p_action is null or jsonb_typeof(p_payload) is distinct from 'object' then raise exception 'ONLINE_INPUT'; end if;
  moderator:=public.online_room_can_manage(r);
  if not moderator and p_action not in ('seat','chat','track') then raise exception 'ONLINE_HOST_ONLY'; end if;
  if p_action in ('play','pause','next','track','suggestions','track_decision','queue_move') and (not r.music_enabled or r.official)
    then raise exception 'ONLINE_MUSIC_LOCKED'; end if;

  case p_action
    when 'seat' then
      str:=p_payload->>'seat';
      if str is null or str !~ '^([1-9]|1[0-9]|20)$' then raise exception 'ONLINE_INPUT'; end if;
      n:=str::integer;
      if exists(select 1 from public.online_room_members where room_id=p_room and user_id<>u and seat=n and lease_until>now())
        then raise exception 'ONLINE_SEAT_TAKEN'; end if;
      update public.online_room_members set seat=null,client_id=null,lease_until=null where room_id=p_room and seat=n and lease_until<=now();
      update public.online_room_members set seat=n where room_id=p_room and user_id=u and seat<>n;
    when 'chat' then
      str:=btrim(p_payload->>'body');
      target:=(p_payload->>'key')::uuid;
      if str is null or length(str) not between 1 and 600 or target is null then raise exception 'ONLINE_INPUT'; end if;
      if exists(select 1 from public.online_room_chat where room_id=p_room and author_id=u and message_key=target)
        then return jsonb_build_object('state','active'); end if;
      if (select count(*) from public.online_room_chat where room_id=p_room and author_id=u and created_at>now()-interval '10 seconds')>=6
        then raise exception 'ONLINE_RATE'; end if;
      insert into public.online_room_chat(room_id,author_id,message_key,body) values(p_room,u,target,str);
      delete from public.online_room_chat where room_id=p_room and id <= (
        select id from public.online_room_chat where room_id=p_room order by id desc offset 300 limit 1);
      area:='chat';
    when 'chat_delete' then
      row_id:=(p_payload->>'id')::bigint;
      delete from public.online_room_chat where room_id=p_room and id=row_id;
      area:='chat';
    when 'track' then
      if not moderator and not r.suggestions then raise exception 'ONLINE_SUGGESTIONS_OFF'; end if;
      str:=p_payload->>'video_id'; label:=btrim(coalesce(p_payload->>'title',''));
      if str is null or str !~ '^[A-Za-z0-9_-]{11}$' or length(label)>96 then raise exception 'ONLINE_INPUT'; end if;
      label:=coalesce(nullif(label,''),'YouTube · '||str);
      if (select count(*) from public.online_room_tracks where room_id=p_room)>=30
        or (not moderator and (select count(*) from public.online_room_tracks where room_id=p_room and requested_by=u and status='pending')>=3)
        then raise exception 'ONLINE_QUEUE_FULL'; end if;
      if r.video_id=str or exists(select 1 from public.online_room_tracks where room_id=p_room and video_id=str)
        then raise exception 'ONLINE_DUPLICATE_TRACK'; end if;
      if moderator and r.video_id is null and not exists(select 1 from public.online_room_tracks where room_id=p_room and status='queued') then
        update public.online_rooms set video_id=str,video_title=label,play_offset=0,play_at=now_at,is_playing=false,play_rev=play_rev+1 where id=p_room;
      else
        insert into public.online_room_tracks(room_id,requested_by,video_id,title,status)
          values(p_room,u,str,label,case when moderator then 'queued' else 'pending' end);
      end if;
    when 'suggestions' then
      if jsonb_typeof(p_payload->'enabled') is distinct from 'boolean' then raise exception 'ONLINE_INPUT'; end if;
      update public.online_rooms set suggestions=(p_payload->>'enabled')::boolean where id=p_room;
    when 'track_decision' then
      target:=(p_payload->>'id')::uuid; str:=p_payload->>'decision';
      if str='remove' then delete from public.online_room_tracks where room_id=p_room and id=target;
      elsif str='approve' then
        update public.online_room_tracks set status='queued' where room_id=p_room and id=target and status='pending';
      else raise exception 'ONLINE_INPUT'; end if;
    when 'queue_move' then
      target:=(p_payload->>'id')::uuid; str:=p_payload->>'direction';
      if str is null or str not in ('up','down') then raise exception 'ONLINE_INPUT'; end if;
      select * into q from public.online_room_tracks where room_id=p_room and id=target and status='queued';
      if q.id is not null then
        if str='up' then select id,sort_key into target,peer_key from public.online_room_tracks
          where room_id=p_room and status='queued' and sort_key<q.sort_key order by sort_key desc limit 1;
        else select id,sort_key into target,peer_key from public.online_room_tracks
          where room_id=p_room and status='queued' and sort_key>q.sort_key order by sort_key limit 1; end if;
        if target is not null then update public.online_room_tracks
          set sort_key=case when id=q.id then peer_key else q.sort_key end where room_id=p_room and id in(q.id,target); end if;
      end if;
    when 'play','pause','next' then
      if (p_payload->>'revision')::integer is distinct from r.play_rev then raise exception 'ONLINE_PLAYBACK_CHANGED'; end if;
      if p_action='next' then
        select * into next_track from public.online_room_tracks where room_id=p_room and status='queued' order by sort_key,id limit 1;
        if next_track.id is not null then delete from public.online_room_tracks where id=next_track.id; end if;
        update public.online_rooms set video_id=next_track.video_id,video_title=next_track.title,play_offset=0,
          play_at=now_at,is_playing=next_track.id is not null,play_rev=play_rev+1 where id=p_room;
      elsif r.video_id is not null and r.is_playing is distinct from (p_action='play') then
        update public.online_rooms set is_playing=(p_action='play'),
          play_offset=case when r.is_playing then r.play_offset+greatest(0,extract(epoch from now_at-r.play_at)) else r.play_offset end,
          play_at=now_at,play_rev=play_rev+1 where id=p_room;
      end if;
    when 'invite' then
      if r.official or r.visibility<>'private' then raise exception 'ONLINE_INPUT'; end if;
      str:=replace(gen_random_uuid()::text||gen_random_uuid()::text,'-','');
      update public.online_rooms set invite_hash=sha256(convert_to(str,'UTF8')),invite_expires_at=now()+interval '1 day' where id=p_room;
      return jsonb_build_object('state','active','invite',str);
    when 'admit','deny','remove_member','transfer' then
      target:=(p_payload->>'id')::uuid;
      if target is null or target=u or target=r.host_id then raise exception 'ONLINE_INPUT'; end if;
      if p_action='transfer' then
        if r.official then raise exception 'ONLINE_INPUT'; end if;
        if not exists(select 1 from public.online_room_members where room_id=p_room and user_id=target and lease_until>now()) then raise exception 'ONLINE_MEMBER_GONE'; end if;
        update public.online_rooms set host_id=target where id=p_room;
      elsif p_action in ('admit','deny') then
        update public.online_room_members set admission=case when p_action='admit' then 'allowed' else 'removed' end
          where room_id=p_room and user_id=target and admission='waiting';
      else
        update public.online_room_members set admission='removed',seat=null,client_id=null,lease_until=null
          where room_id=p_room and user_id=target and admission='allowed';
        delete from public.online_room_tracks where room_id=p_room and requested_by=target and status='pending';
      end if;
    when 'close' then
      if r.official then raise exception 'ONLINE_INPUT'; end if;
      update public.online_rooms set closed_at=now(),invite_hash=null,invite_expires_at=null where id=p_room;
      update public.online_room_members set seat=null,client_id=null,lease_until=null where room_id=p_room and seat is not null;
      reply:=jsonb_build_object('state','closed');
    else raise exception 'ONLINE_INPUT';
  end case;
  perform public.online_room_notify(p_room,area);
  return jsonb_build_object('state','active')||reply;
end;
$$;

