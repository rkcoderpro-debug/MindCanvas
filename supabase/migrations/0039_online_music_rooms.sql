create table if not exists public.online_rooms (
  id uuid primary key default gen_random_uuid(),
  kind text not null default 'music' check (kind = 'music'),
  created_by uuid references auth.users(id) on delete set null,
  host_id uuid references auth.users(id) on delete set null,
  name text not null check (char_length(name) between 1 and 64),
  topic text not null default '' check (char_length(topic) <= 160),
  visibility text not null check (visibility in ('public','private')),
  layout text not null check (layout in ('classroom','compact')),
  official boolean not null default false,
  music_enabled boolean not null default true,
  requires_approval boolean not null default false,
  suggestions boolean not null default false,
  invite_hash bytea,
  invite_expires_at timestamptz,
  video_id text check (video_id ~ '^[A-Za-z0-9_-]{11}$'),
  video_title text,
  attribution text,
  is_playing boolean not null default false,
  play_loop boolean not null default false,
  play_offset numeric not null default 0,
  play_at timestamptz not null default now(),
  play_rev integer not null default 0,
  created_at timestamptz not null default now(),
  closed_at timestamptz
);
create index if not exists online_rooms_creator_idx on public.online_rooms(created_by) where closed_at is null;
create index if not exists online_rooms_visible_idx on public.online_rooms(visibility, created_at desc) where closed_at is null;

create table if not exists public.online_room_members (
  room_id uuid not null references public.online_rooms(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  admission text not null default 'allowed' check (admission in ('allowed','waiting','removed')),
  seat smallint check (seat between 1 and 20),
  client_id uuid,
  lease_until timestamptz,
  last_seen timestamptz not null default now(),
  joined_at timestamptz not null default now(),
  primary key (room_id,user_id),
  unique (room_id,seat),
  check ((seat is null and client_id is null and lease_until is null)
      or (seat is not null and client_id is not null and lease_until is not null and admission = 'allowed'))
);
create index if not exists online_room_members_user_idx on public.online_room_members(user_id,room_id);
create index if not exists online_room_members_lease_idx on public.online_room_members(room_id,lease_until) where seat is not null;

create table if not exists public.online_room_chat (
  id bigint generated always as identity primary key,
  room_id uuid not null references public.online_rooms(id) on delete cascade,
  author_id uuid references auth.users(id) on delete set null,
  message_key uuid not null,
  body text not null check (char_length(btrim(body)) between 1 and 600),
  created_at timestamptz not null default now(),
  unique (room_id,author_id,message_key)
);
create index if not exists online_room_chat_room_idx on public.online_room_chat(room_id,id);
create index if not exists online_room_chat_rate_idx on public.online_room_chat(room_id,author_id,created_at);

create table if not exists public.online_room_tracks (
  id uuid primary key default gen_random_uuid(),
  room_id uuid not null references public.online_rooms(id) on delete cascade,
  requested_by uuid references auth.users(id) on delete set null,
  video_id text not null check (video_id ~ '^[A-Za-z0-9_-]{11}$'),
  title text not null check (char_length(title) between 1 and 96),
  status text not null check (status in ('queued','pending')),
  sort_key bigint generated by default as identity,
  created_at timestamptz not null default now(),
  unique (room_id,video_id)
);
create index if not exists online_room_tracks_queue_idx on public.online_room_tracks(room_id,status,sort_key);

