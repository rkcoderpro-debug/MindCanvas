import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";
if(!process.env.PGLITE_ENTRY) throw new Error("Set PGLITE_ENTRY to PGlite dist/index.js");
const url=pathToFileURL(process.env.PGLITE_ENTRY);
const {PGlite}=await import(url);
const {pgcrypto}=await import(new URL("./contrib/pgcrypto.js",url));
const db=new PGlite({extensions:{pgcrypto}});
const uid=n=>"66000000-0000-4000-8000-"+String(n).padStart(12,"0");
const [owner,recipient,other,unverified,root,child,outside,project,attach,embed,file,quiz,deck,card,staged]=Array.from({length:15},(_,i)=>uid(i+1));
const link=n=>String(n).padStart(48,"0");
const rows=(q,args=[])=>db.query(q,args).then(x=>x.rows);
const value=(q,args=[])=>rows(q,args).then(x=>x[0]?.v);
const role=async(name)=>db.exec("reset role; set role "+name);
const manage=(actor,k,id,op,addr,right,token)=>value("select ws_share_manage($1,$2,$3,$4,$5,$6,$7) as v",[actor,k,id,op,addr,right,token]);
const open=(token,actor=null,proof=null,k=null,id=null,op="view",payload={})=>value("select ws_share_read($1,$2,$3,$4,$5,$6,$7::jsonb) as v",[token,actor,proof,k,id,op,JSON.stringify(payload)]);
const write=(token,actor,k,id,op,payload)=>value("select ws_share_write($1,$2,$3,$4,$5,$6::jsonb) as v",[token,actor,k,id,op,JSON.stringify(payload)]);
const mail=(token,actor,op,code=null,proof=null)=>value("select ws_share_mail($1,$2,$3,$4,$5) as v",[token,actor,op,code,proof]);
try{
  await db.exec(`
  create role anon; create role authenticated; create role service_role;
  create schema auth; create schema storage;
  grant usage on schema public,auth,storage to anon,authenticated,service_role;
  create table auth.users(id uuid primary key,email text,raw_user_meta_data jsonb,email_confirmed_at timestamptz);
  create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
  create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
  create table storage.objects(bucket_id text,name text,metadata jsonb,primary key(bucket_id,name));
  create function storage.foldername(name text) returns text[] language sql immutable as $$ select string_to_array(name,'/') $$;
  alter table storage.objects enable row level security;
  grant select,insert,delete on storage.objects to authenticated;`);
  const migrate=name=>readFile(new URL("../migrations/"+name,import.meta.url),"utf8").then(sql=>db.exec(sql));
  await migrate("0001_mindcanvas.sql");
  await migrate("0005_flashcards.sql");
  await db.exec(`alter table notes add column deleted_at timestamptz,add column revision bigint not null default 0,add column thumbnail jsonb;
    create table quiz_tests(id uuid primary key,user_id uuid references auth.users,title text,description text,questions jsonb,updated_at timestamptz default now());`);
  await migrate("0044_workspace_folder_files.sql");
  await migrate("0045_workspace_sharing.sql");
  await migrate("0045_workspace_sharing.sql");
  await rows("insert into auth.users(id,email,email_confirmed_at) values ($1,'owner@test.test',now()),($2,'recipient@test.test',now()),($3,'other@test.test',now()),($4,'unverified@test.test',null)",[owner,recipient,other,unverified]);
  await rows("insert into folders(id,user_id,name) values ($1,$2,'DSA'),($3,$2,'Private')",[root,owner,outside]);
  await rows("insert into folders(id,user_id,name,parent_id) values ($1,$2,'Lab',$3)",[child,owner,root]);
  const digest="f".repeat(64);
  const blueprint={id:project,title:"Lesson",media:[{src:"mindcanvas-asset:"+digest}],embeds:[{id:embed,kind:"document",documentId:attach}]};
  await rows("insert into notes(id,user_id,title,folder_id,content) values ($1,$2,'Lesson',$3,$4::jsonb)",[project,owner,child,JSON.stringify({version:2,board:blueprint})]);
  await rows("insert into workspace_files(id,user_id,folder_id,name,size_bytes,ready) values ($1,$2,$3,'lab.cpp',4,true)",[file,owner,child]);
  await rows("insert into workspace_files(id,user_id,canvas_id,embed_id,name,size_bytes,ready) values ($1,$2,$3,$4,'Notes.pdf',4,true)",[attach,owner,project,embed]);
  await rows("insert into quiz_tests(id,user_id,title,description,questions) values($1,$2,'Quiz','Practice',$3::jsonb)",[quiz,owner,JSON.stringify([{id:uid(31),prompt:"2+2?",options:["4","5","6","7"],correctIndex:0,explanation:"Addition"}])]);
  await rows("insert into flashcard_decks(id,user_id,name,folder_id) values ($1,$2,'Deck',$3)",[deck,owner,child]);
  await rows("insert into flashcards(id,deck_id,user_id,front,back,repetitions) values ($1,$2,$3,'Front','Back',7)",[card,deck,owner]);
  await rows("insert into storage.objects values('workspace-files',$1,jsonb_build_object('size',7))",[owner+"/"+staged]);
  await role("service_role");
  await assert.rejects(manage(other,"folder",root,"set","","editor",link(1)),/SHARE_FORBIDDEN/);
  await manage(owner,"folder",root,"set","","viewer",link(1));
  assert.equal((await open(link(1))).data[0].id,child);
  assert.equal((await open(link(1),null,null,"file",file,"download")).object,file);
  assert.equal((await open(link(1),null,null,"canvas",project,"asset",{digest})).ok,true);
  assert.equal((await open(link(1),null,null,"canvas",project)).data.files[0].id,attach);
  assert.equal((await open(link(1),null,null,"flashcard",deck)).data[0].repetitions,undefined);
  await assert.rejects(open(link(1),null,null,"canvas",project,"asset",{digest:"0".repeat(64)}),/SHARE_FORBIDDEN/);
  await assert.rejects(open(link(1),null,null,"folder",outside),/SHARE_FORBIDDEN/);
  await assert.rejects(write(link(1),other,"file",file,"rename",{title:"No"}),/SHARE_FORBIDDEN/);
  await manage(owner,"file",attach,"set","","viewer",link(2));
  assert.equal((await open(link(2))).title,"Notes.pdf");
  await assert.rejects(open(link(2),null,null,"canvas",project),/SHARE_FORBIDDEN/);
  await manage(owner,"file",file,"set","","viewer",link(7));
  await manage(owner,"folder",root,"set","","editor",link(99));
  assert.equal((await open(link(1))).role,"viewer");
  assert.equal((await open(link(1))).signInToEdit,true);
  assert.equal((await open(link(1),other)).role,"editor");
  await assert.rejects(write(link(1),null,"file",file,"rename",{title:"No"}),/SHARE_FORBIDDEN/);
  await write(link(1),other,"folder",child,"mkdir",{title:"New folder"});
  const fileVersion=(await open(link(1),other,null,"file",file)).data.revision;
  assert.deepEqual(await write(link(1),other,"file",file,"replace",{object:staged,size:7,revision:fileVersion}),{id:file,old:file});
  await assert.rejects(write(link(1),other,"file",file,"replace",{object:staged,size:7,revision:fileVersion}),/SHARE_CONFLICT/);
  assert.equal((await open(link(1),null,null,"file",file,"download")).object,staged);
  const cs=await open(link(1),other,null,"canvas",project);
  await write(link(1),other,"canvas",project,"canvas",{revision:cs.data.revision,board:{...blueprint,title:"Updated",media:[{src:"injected"}],embeds:[]}});
  const edited=await open(link(1),other,null,"canvas",project);
  assert.equal(edited.title,"Updated");assert.deepEqual(edited.data.board.media,blueprint.media);assert.deepEqual(edited.data.board.embeds,blueprint.embeds);
  await assert.rejects(write(link(1),other,"canvas",project,"canvas",{revision:cs.data.revision,board:blueprint}),/SHARE_CONFLICT/);
  const deckView=await open(link(1),other,null,"flashcard",deck);
  await write(link(1),other,"flashcard",deck,"card",{id:card,revision:deckView.data[0].revision,front:"New",back:"Back"});
  await assert.rejects(write(link(1),other,"flashcard",deck,"card",{id:card,revision:deckView.data[0].revision,front:"Stale",back:"Back"}),/SHARE_CONFLICT/);
  await manage(owner,"quiz",quiz,"set","","viewer",link(3));
  const q=await open(link(3));
  assert.equal(q.data.questions[0].correctIndex,undefined);
  assert.equal(q.data.questions[0].explanation,undefined);
  assert.equal((await open(link(3),null,null,null,null,"submit",{revision:q.data.revision,answers:[0]})).score,1);
  await manage(owner,"quiz",quiz,"set","recipient@test.test","editor",link(4));
  assert.equal((await open(link(4),other)).state,"sign-in");
  assert.equal((await open(link(4),recipient)).data.questions[0].correctIndex,0);
  await write(link(4),recipient,"quiz",quiz,"quiz",{title:"Updated quiz",description:"",revision:q.data.revision,questions:[{...q.data.questions[0],correctIndex:1}]});
  await assert.rejects(open(link(3),null,null,null,null,"submit",{revision:q.data.revision,answers:[0]}),/SHARE_CONFLICT/);
  await manage(owner,"file",file,"set","recipient@test.test","viewer",link(5));
  assert.equal((await open(link(5))).state,"verify");
  assert.equal((await mail(link(5),null,"challenge","hash")).email,"recipient@test.test");
  await assert.rejects(mail(link(5),null,"challenge","second"),/SHARE_RATE/);
  assert.deepEqual(await mail(link(5),null,"verify","no","proof"),{ok:false});
  assert.deepEqual(await mail(link(5),null,"verify","hash","proof"),{ok:true});
  assert.equal((await open(link(5),null,"proof")).title,"lab.cpp");
  assert.equal((await open(link(5),recipient)).state,"ok");
  assert.equal((await value("select ws_share_received($1) as v",[recipient])).length,2);
  await manage(owner,"file",file,"remove","recipient@test.test","viewer",null);
  await assert.rejects(open(link(5),null,"proof"),/SHARE_FORBIDDEN/);
  await manage(owner,"file",file,"set","unverified@test.test","editor",link(8));
  assert.equal((await open(link(8),unverified)).state,"sign-in");
  await db.exec("reset role");
  await rows("update workspace_files set folder_id=$1 where id=$2",[outside,file]);
  assert.equal((await rows("select repetitions from flashcards where id=$1",[card]))[0].repetitions,7);
  await role("service_role");
  await assert.rejects(open(link(1),other,null,"file",file),/SHARE_FORBIDDEN/);
  assert.equal((await open(link(7))).state,"ok");
  await manage(owner,"folder",root,"remove","","viewer",null);
  await assert.rejects(open(link(1)),/SHARE_FORBIDDEN/);
  for(const actor of ["anon","authenticated"]){
    await role(actor);
    await assert.rejects(open(link(2)),/permission denied/);
    await assert.rejects(rows("select token from workspace_share_grants"),/permission denied/);
  }
  console.log("Workspace sharing SQL passed: anonymous and verified emails, editor writes, attachment and folder scopes, revoke, and RLS.");
} finally { await db.close(); }
